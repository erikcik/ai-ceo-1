#!/usr/bin/env bash
# Generates every level-3 evidence artifact by running the checks, so nothing in them is
# typed by hand and nothing can drift from REPORT.md.
#
#   bash evidence/level-3/make-level3-checks.sh
#
# Writes: evidence/level-3/wordcount.txt
#         evidence/level-3/claim-coverage.md
#         evidence/level-3/verify.txt
#
# Re-run it after ANY edit to REPORT.md, claims/claim-map.md or sources/*.md.
# Everything below reads from disk; the only hand-written inputs are the SPEC table
# (report line -> claim id -> key#Qn) and the classification notes in the number audit.
set -u

R=REPORT.md
OUT=evidence/level-3
WC=$OUT/wordcount.txt
COV=$OUT/claim-coverage.md
VER=$OUT/verify.txt

# report line where the sentence starts | claim id | key#Qn
SPEC='
